// Vendors the brand-logo SVG paths for the blocked-services catalogue from
// simple-icons into src/lib/serviceLogos.ts, so the icons ship bundled (offline,
// no runtime dependency). The SVG path data from simple-icons is CC0; the marks
// themselves are trademarks of their respective owners.
//
// Regenerate after changing the service catalogue:
//   node scripts/gen-service-logos.mjs
import { writeFileSync } from "node:fs";
import * as si from "simple-icons";

// Service id (crates/justdns-filter/src/services.rs) -> simple-icons export name.
const MAP = {
  facebook: "siFacebook",
  instagram: "siInstagram",
  tiktok: "siTiktok",
  x: "siX",
  snapchat: "siSnapchat",
  reddit: "siReddit",
  pinterest: "siPinterest",
  youtube: "siYoutube",
  netflix: "siNetflix",
  twitch: "siTwitch",
  // disneyplus: simple-icons dropped the Disney+ mark on a trademark request, so
  // there is no logo to vendor — the UI falls back to a coloured-initial tile.
  whatsapp: "siWhatsapp",
  telegram: "siTelegram",
  discord: "siDiscord",
  steam: "siSteam",
  epicgames: "siEpicgames",
  spotify: "siSpotify",
};

const entries = [];
const missing = [];
for (const [id, name] of Object.entries(MAP)) {
  const icon = si[name];
  if (!icon || !icon.path) {
    missing.push(`${id} (${name})`);
    continue;
  }
  entries.push({ id, path: icon.path, hex: `#${icon.hex}`, title: icon.title });
}

if (missing.length) {
  console.error("Missing simple-icons for:", missing.join(", "));
  process.exit(1);
}

const body = entries
  .map((e) => `  ${e.id}: { path: ${JSON.stringify(e.path)}, hex: ${JSON.stringify(e.hex)} },`)
  .join("\n");

const out = `// AUTO-GENERATED by scripts/gen-service-logos.mjs — do not edit by hand.
// Brand-logo SVG paths for the blocked-services catalogue, vendored from
// simple-icons (CC0 path data; the marks are trademarks of their owners) so the
// icons ship bundled with the app, with no runtime icon dependency.
//
// Regenerate: node scripts/gen-service-logos.mjs

/** One service's logo: a single SVG path on a 24x24 viewBox, plus the brand's
 *  signature colour. */
export interface ServiceLogo {
  path: string;
  hex: string;
}

/** Keyed by the bare service id (\`tiktok\`, not \`svc:tiktok\`). */
export const SERVICE_LOGOS: Record<string, ServiceLogo> = {
${body}
};
`;

writeFileSync(new URL("../src/lib/serviceLogos.ts", import.meta.url), out);
console.log(`Wrote ${entries.length} service logos to src/lib/serviceLogos.ts`);
