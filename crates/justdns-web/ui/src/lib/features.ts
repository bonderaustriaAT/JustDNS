import type { MessageKey } from "./messages";
import type { Role } from "./api";

/** The minimum role that can meaningfully use a feature. The guide lists only
 *  entries the signed-in role can act on, so a viewer is never pointed at a
 *  page they cannot open. */
export type FeatureRole = Role;

/** One catalogued feature: what it is (title/description as i18n keys, so both
 *  languages are enforced by the Catalog type and the CI check), where it
 *  lives (route), who it is for (roles), which guide explains it in depth
 *  (slug into docs/guides on GitHub), and — optionally — the release it
 *  appeared in, which drives the "new in this version" card and the dot in
 *  the guide. `keywords` are search-only terms in both languages; they are an
 *  index, not UI text, so they live here rather than in messages. */
export interface FeatureEntry {
  id: string;
  /** Grouping chip in the guide; an existing nav.section message key. */
  category: MessageKey;
  titleKey: MessageKey;
  descKey: MessageKey;
  /** In-app route the entry navigates to. */
  route: string;
  roles: FeatureRole[];
  /** Slug of the GitHub guide (`docs/guides/<slug>.de.md` / `.md`), if one
   *  exists; omit for features covered elsewhere. */
  guide?: string;
  /** The release this feature shipped in, e.g. "0.49.1". */
  since?: string;
  keywords: { de: string[]; en: string[] };
  /** The ICONS key for the entry's mark. */
  icon: string;
}

