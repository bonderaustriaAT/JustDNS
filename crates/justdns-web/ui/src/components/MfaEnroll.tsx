import { useEffect, useState } from "react";

import { ApiError, type MfaSetup } from "../lib/api";
import { useI18n } from "../lib/i18n";
import styles from "../pages/Account.module.css";

/** The shared "scan, confirm, save your recovery codes" enrolment flow, used
 *  both on the account page (voluntary) and during a login that requires MFA.
 *  The two callers differ only in which endpoints they hit, so those are passed
 *  in: `begin` mints the secret and codes, `confirm` verifies a code, and
 *  `onDone` runs once MFA is active. */
export function MfaEnroll({
  begin,
  confirm,
  onDone,
  doneLabel,
}: {
  begin: () => Promise<MfaSetup>;
  confirm: (code: string) => Promise<void>;
  onDone: () => void;
  doneLabel: string;
}) {
  const { t } = useI18n();
  const [setup, setSetup] = useState<MfaSetup | null>(null);
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [copied, setCopied] = useState(false);

  // Mint the secret once, when the flow opens.
  useEffect(() => {
    let live = true;
    begin()
      .then((result) => {
        if (live) setSetup(result);
      })
      .catch(() => {
        if (live) setError(t("auth.loginFailed"));
      });
    return () => {
      live = false;
    };
    // `begin` is a fresh closure per render by design; run this once.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  async function onConfirm() {
    setError(null);
    setBusy(true);
    try {
      await confirm(code.trim());
      onDone();
    } catch (cause) {
      setError(
        cause instanceof ApiError && cause.status === 401
          ? t("auth.invalidCode")
          : t("auth.loginFailed"),
      );
      setBusy(false);
    }
  }

  async function copyRecovery() {
    if (!setup) return;
    try {
      await navigator.clipboard.writeText(setup.recoveryCodes.join("\n"));
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      // Clipboard access can be denied; the codes are visible to copy by hand.
    }
  }

  if (!setup) {
    return error ? (
      <p className={styles.noticeErr} role="alert">
        {error}
      </p>
    ) : (
      <p className={styles.hint}>{t("mfa.enabling")}</p>
    );
  }

  return (
    <div className={styles.enroll}>
      <div className={styles.step}>
        <span className={styles.stepTitle}>{t("mfa.step1")}</span>
        <span className={styles.hint}>{t("mfa.step1Hint")}</span>
        <div
          className={styles.qr}
          // The SVG is generated by our own server from the otpauth URI.
          dangerouslySetInnerHTML={{ __html: setup.qrSvg }}
          role="img"
          aria-label="QR"
        />
        <span className={styles.hint}>{t("mfa.manualKey")}</span>
        <code className={styles.secret}>{setup.secret}</code>
      </div>

      <div className={styles.step}>
        <span className={styles.stepTitle}>{t("mfa.step3")}</span>
        <span className={styles.hint}>{t("mfa.recoveryHint")}</span>
        <div className={styles.codeGrid}>
          {setup.recoveryCodes.map((rc) => (
            <span key={rc}>{rc}</span>
          ))}
        </div>
        <div className={styles.actions}>
          <button type="button" className={styles.button} onClick={copyRecovery}>
            {copied ? t("mfa.copied") : t("mfa.copyRecovery")}
          </button>
        </div>
      </div>

      <div className={styles.step}>
        <span className={styles.stepTitle}>{t("mfa.step2")}</span>
        {error && (
          <p className={styles.noticeErr} role="alert">
            {error}
          </p>
        )}
        <div className={styles.row}>
          <label className={styles.field}>
            <span className={styles.label}>{t("auth.code")}</span>
            <input
              className={styles.input}
              inputMode="numeric"
              autoComplete="one-time-code"
              value={code}
              onChange={(e) => setCode(e.target.value)}
              placeholder="000000"
            />
          </label>
        </div>
        <div className={styles.actions}>
          <button
            type="button"
            className={styles.buttonPrimary}
            onClick={onConfirm}
            disabled={busy || code.trim().length < 6}
          >
            {busy ? t("mfa.enabling") : doneLabel}
          </button>
        </div>
      </div>
    </div>
  );
}
